"""Compare a new snapshot with the published one: commit message and ``CHANGELOG.md`` entry."""

import json
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ss14help_pipeline.build import BuildResult
from ss14help_pipeline.emit import canonical
from ss14help_pipeline.models import Manifest

CHANGELOG_FILE = "CHANGELOG.md"
MAX_IDS_PER_LINE = 30

COLLECTIONS: dict[str, tuple[str, str]] = {
    # collection → (file, id field); the collection is also the key inside the file.
    "reagents": ("reagents.json", "id"),
    "reactions": ("recipes.json", "id"),
    "cooking": ("recipes.json", "id"),
    "mixers": ("recipes.json", "id"),
    "sources": ("sources.json", "entity"),
    "entities": ("entities.json", "id"),
}

Items = dict[str, dict[str, Any]]
"""Collection → id → item (as JSON)."""


@dataclass
class Change:
    added: list[str] = field(default_factory=list)
    removed: list[str] = field(default_factory=list)
    changed: list[str] = field(default_factory=list)

    def __bool__(self) -> bool:
        return bool(self.added or self.removed or self.changed)


@dataclass
class SnapshotDiff:
    old: Manifest | None
    new: Manifest
    changes: dict[str, Change]

    @property
    def has_changes(self) -> bool:
        return self.old is None or any(self.changes.values())

    def summary(self) -> str:
        """``+3 reactions, -1 cooking, ~5 changed``, or ``no data changes``."""
        if self.old is None:
            return "initial snapshot"
        parts = [f"+{len(c.added)} {k}" for k, c in self.changes.items() if c.added]
        parts += [f"-{len(c.removed)} {k}" for k, c in self.changes.items() if c.removed]
        changed = sum(len(c.changed) for c in self.changes.values())
        if changed:
            parts.append(f"~{changed} changed")
        return ", ".join(parts) or "no data changes"

    def commit_message(self) -> str:
        old = self.old.sha[:7] if self.old else "none"
        return f"data({self.new.server}): {old} → {self.new.sha[:7]} ({self.summary()})"

    def changelog_entry(self) -> str:
        new = self.new
        if self.old is None:
            span = f"[`{new.sha[:7]}`]({new.repo}/commit/{new.sha})"
        else:
            span = (
                f"[`{self.old.sha[:7]}` → `{new.sha[:7]}`]"
                f"({new.repo}/compare/{self.old.sha}...{new.sha})"
            )
        lines = [f"## {new.commit_date:%Y-%m-%d} · {span}", ""]
        if self.old is None:
            counts = ", ".join(f"{n} {k}" for k, n in new.counts.items())
            lines.append(f"- Initial snapshot: {counts}")
        for key, change in self.changes.items():
            for verb, ids in (
                ("added", change.added),
                ("removed", change.removed),
                ("changed", change.changed),
            ):
                if ids:
                    lines.append(f"- {key.capitalize()} {verb}: {_id_list(ids)}")
        warnings = _warning_line(self.old, new)
        if warnings:
            lines.append(warnings)
        return "\n".join(lines) + "\n"


def load_items(out_dir: Path) -> Items | None:
    """Items of the published snapshot in ``out_dir``, if there is one."""
    if not (out_dir / "manifest.json").exists():
        return None
    docs = {
        file: json.loads((out_dir / file).read_text(encoding="utf-8"))
        for file in {f for f, _ in COLLECTIONS.values()}
    }
    return {
        key: {item[id_field]: item for item in docs[file][key]}
        for key, (file, id_field) in COLLECTIONS.items()
    }


def result_items(result: BuildResult) -> Items:
    docs = {name: model.model_dump(mode="json") for name, model in result.files.items()}
    return {
        key: {item[id_field]: item for item in docs[file][key]}
        for key, (file, id_field) in COLLECTIONS.items()
    }


def diff_snapshots(
    old_manifest: Manifest | None, old: Items | None, result: BuildResult
) -> SnapshotDiff:
    new = result_items(result)
    changes: dict[str, Change] = {}
    for key in COLLECTIONS:
        before, after = (old or {}).get(key, {}), new[key]
        changes[key] = Change(
            added=sorted(after.keys() - before.keys()) if old is not None else [],
            removed=sorted(before.keys() - after.keys()),
            changed=sorted(
                i
                for i in after.keys() & before.keys()
                if canonical(after[i]) != canonical(before[i])
            ),
        )
    return SnapshotDiff(old=old_manifest, new=result.manifest, changes=changes)


def prepend_changelog(out_dir: Path, entry: str, server_name: str) -> Path:
    """Newest entry first, under a fixed title."""
    path = out_dir / CHANGELOG_FILE
    title = f"# {server_name} data changelog\n\nGenerated by the sync job. Newest first.\n"
    body = ""
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        start = existing.find("\n## ")
        body = existing[start + 1 :] if start >= 0 else ""
    path.write_text(f"{title}\n{entry}\n{body}".rstrip("\n") + "\n", encoding="utf-8", newline="\n")
    return path


def _id_list(ids: list[str]) -> str:
    shown = ", ".join(f"`{i}`" for i in ids[:MAX_IDS_PER_LINE])
    rest = len(ids) - MAX_IDS_PER_LINE
    return f"{shown} and {rest} more" if rest > 0 else shown


def _warning_line(old: Manifest | None, new: Manifest) -> str | None:
    after = Counter(w.code for w in new.warnings)
    before = Counter(w.code for w in old.warnings) if old else Counter[str]()
    if after == before:
        return None
    new_codes = ", ".join(f"`{c}` +{n}" for c, n in sorted((after - before).items()))
    line = f"- Warnings: {sum(before.values())} → {sum(after.values())}"
    return f"{line} ({new_codes})" if new_codes else line
